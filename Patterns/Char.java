public class Char {
        public static void main(String [] args){
            // char ch='A';
            int k=64;
            for(int i=1;i<5;i++){
                for(int j=1;j<=i;j++){
                    // System.out.print(" ");
                    k++;
                    System.out.print((char)(k)+" ");
                }
                System.out.println();
            }
        }
}
